def main():
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    for s in SLIDES:
        sl = prs.slides.add_slide(prs.slide_layouts[1])          # 제목 + 내용
        sl.shapes.title.text = s["title"]
        body = sl.placeholders[1].text_frame
        body.clear()
        lines = ([s["label"]] if s.get("label") else []) + s["lines"]
        for i, t in enumerate(lines):
            p = body.paragraphs[0] if i == 0 else body.add_paragraph()
            p.text = t
            p.font.size = Pt(20 if t not in ("주의", "전원 넣기 전 확인") else 22)
            p.font.bold = t.startswith("STEP") or t in ("주의", "전원 넣기 전 확인")
        sl.notes_slide.notes_text_frame.text = s["notes"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    prs.save(str(OUT))
    print("saved", OUT)


if __name__ == "__main__":
    main()
